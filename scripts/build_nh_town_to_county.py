"""One-off codegen — fetch Census 2020 NH county-subdivision relationship file
and emit src/casesignal/etl/adapters/cold_case_nh_doj/county_fips.py.

Run manually:
    python3 scripts/build_nh_town_to_county.py

Output is committed; this script never runs at ingest time.

Source: https://www2.census.gov/geo/docs/maps-data/data/rel2020/cousub/
    tab20_cousub20_cousub10_st33.txt (NH-only county-subdivision relationship file)

In New Hampshire, every populated place is a county subdivision (town/city) —
NH uses the New England town system, so cities and towns are 1:1 with counties.
The 10-digit COUSUB GEOID encodes state(2)|county(3)|cousub(5), so we extract
the county FIPS by string-slicing the GEOID. No ambiguity, no overlap.
"""

from __future__ import annotations

import csv
import io
import re
import urllib.request
from pathlib import Path

URL = (
    "https://www2.census.gov/geo/docs/maps-data/data/rel2020/cousub/"
    "tab20_cousub20_cousub10_st33.txt"
)
OUT = (
    Path(__file__).resolve().parent.parent
    / "src/casesignal/etl/adapters/cold_case_nh_doj/county_fips.py"
)

# Hand-curated aliases for villages / sub-areas referenced by NH DOJ but
# absent from the Census cousub file (Census uses parent town only).
# These get merged into the generated dict so they survive regeneration.
HAND_CURATED_ALIASES: dict[str, str] = {
    "center ossipee": "33003",   # village within Ossipee town (Carroll)
    "north haverhill": "33009",  # village within Haverhill town (Grafton)
    "pinkham notch": "33007",    # mountain pass in unincorporated Coos
}

# NH county FIPS -> human name (for the codegen comment header).
NH_COUNTIES: dict[str, str] = {
    "33001": "Belknap",
    "33003": "Carroll",
    "33005": "Cheshire",
    "33007": "Coos",
    "33009": "Grafton",
    "33011": "Hillsborough",
    "33013": "Merrimack",
    "33015": "Rockingham",
    "33017": "Strafford",
    "33019": "Sullivan",
}


def _strip_suffix(name: str) -> str:
    """Strip Census legal/statistical suffix from a place name."""
    return re.sub(
        r"\s+(town|city|CDP|borough|village|township|gore|grant|location|purchase)$",
        "",
        name,
        flags=re.IGNORECASE,
    ).strip()


# When two NH places normalize to the same name after suffix-stripping
# (e.g., "Wentworth town" in Grafton vs "Wentworth location" in Coos),
# prefer the row whose Census suffix has higher priority. Towns/cities are
# the populated kind; locations/grants/gores/purchases are largely uninhabited.
_SUFFIX_PRIORITY: dict[str, int] = {
    "city": 100,
    "town": 90,
    "borough": 80,
    "township": 70,
    "village": 60,
    "CDP": 50,
    "location": 10,
    "grant": 5,
    "gore": 5,
    "purchase": 5,
}


def _suffix_rank(namelsad: str) -> int:
    m = re.search(
        r"\s+(town|city|CDP|borough|village|township|gore|grant|location|purchase)$",
        namelsad,
        flags=re.IGNORECASE,
    )
    if not m:
        return 0
    return _SUFFIX_PRIORITY.get(m.group(1).lower(), 0)


def main() -> None:
    print(f"Fetching {URL} ...")
    with urllib.request.urlopen(URL, timeout=60) as resp:
        data = resp.read().decode("utf-8-sig")

    reader = csv.DictReader(io.StringIO(data), delimiter="|")
    # Use 2020 GEOID + name; dedupe across the 2020->2010 cross-product rows.
    # For each normalized place name, keep the assignment with the highest-
    # priority Census suffix (town > city > ... > location > grant).
    place_to_county: dict[str, str] = {}
    place_to_rank: dict[str, int] = {}
    for row in reader:
        geoid = row["GEOID_COUSUB_20"]
        if not geoid.startswith("33") or len(geoid) != 10:
            continue
        cfips = geoid[:5]  # state(2) + county(3)
        if cfips not in NH_COUNTIES:
            continue
        namelsad = row["NAMELSAD_COUSUB_20"]
        place = _strip_suffix(namelsad).lower()
        if not place:
            continue
        rank = _suffix_rank(namelsad)
        cur_rank = place_to_rank.get(place, -1)
        if rank > cur_rank:
            place_to_county[place] = cfips
            place_to_rank[place] = rank
        elif rank == cur_rank and place_to_county.get(place) != cfips:
            print(
                f"  WARN: ambiguous {place!r}: "
                f"{place_to_county[place]} vs {cfips} (same rank, keeping first)"
            )

    # Merge hand-curated aliases (override any collision — these come from
    # actual corpus references that the Census cousub file lacks).
    for alias, cfips in HAND_CURATED_ALIASES.items():
        place_to_county[alias] = cfips

    lines = [
        '"""NH town -> county FIPS lookup.',
        "",
        "Generated by scripts/build_nh_town_to_county.py from Census 2020",
        "county-subdivision relationship file. Do not edit by hand (regenerate",
        "via the script instead). Every NH populated place is a county",
        "subdivision under the New England town system, so the mapping is 1:1.",
        "",
        "NH counties (FIPS 33001-33019, odd-only):",
    ]
    for cfips in sorted(NH_COUNTIES):
        lines.append(f"  {cfips} {NH_COUNTIES[cfips]}")
    lines += [
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "_TOWN_TO_COUNTY: dict[str, str] = {",
    ]
    for place in sorted(place_to_county):
        cfips = place_to_county[place]
        lines.append(f"    {place!r}: {cfips!r},")
    lines += [
        "}",
        "",
        "",
        "def lookup(town: str | None) -> str | None:",
        '    """Case-insensitive town -> 5-digit county FIPS. None if unknown."""',
        "    if not town:",
        "        return None",
        "    return _TOWN_TO_COUNTY.get(town.strip().lower())",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(place_to_county)} NH places -> {OUT}")


if __name__ == "__main__":
    main()
