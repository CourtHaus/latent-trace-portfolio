import type { Metadata, Viewport } from "next";
import { saira, pinnacle, splineMono } from "@/lib/fonts";
import { NuqsAdapter } from "nuqs/adapters/next/app";
import { StatusStrip } from "@/components/chrome/StatusStrip";
import { SiteNav } from "@/components/chrome/SiteNav";
import { SiteFooter } from "@/components/chrome/SiteFooter";
import { ThemeProvider } from "@/components/chrome/ThemeProvider";
import { AnalyticsProvider } from "@/components/chrome/AnalyticsProvider";
import { SpeedInsights } from "@vercel/speed-insights/next";
import "./globals.css";

const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000";
const SITE_DESCRIPTION =
  "Public analytics and case data for unsolved cold cases.";

export const viewport: Viewport = {
  colorScheme: "dark",
  themeColor: "#05090d",
};

export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: {
    default: "Latent Trace",
    template: "%s · Latent Trace",
  },
  description: SITE_DESCRIPTION,
  // Social card image is generated by app/opengraph-image.tsx (+ twitter-image.tsx)
  // and applies to every route that doesn't define its own — no static asset to
  // keep in sync.
  openGraph: {
    type: "website",
    siteName: "Latent Trace",
    title: "Latent Trace",
    description: SITE_DESCRIPTION,
    url: "/",
  },
  twitter: {
    card: "summary_large_image",
    title: "Latent Trace",
    description: SITE_DESCRIPTION,
  },
};

// Sitewide structured data. WebSite + SearchAction lets search engines surface a
// sitelinks search box pointing at the cold-case search. No per-victim Person
// schema — victim identities are sensitive and out of scope for markup.
const WEBSITE_JSON_LD = {
  "@context": "https://schema.org",
  "@type": "WebSite",
  name: "Latent Trace",
  url: SITE_URL,
  description: SITE_DESCRIPTION,
  potentialAction: {
    "@type": "SearchAction",
    target: {
      "@type": "EntryPoint",
      urlTemplate: `${SITE_URL}/cold-cases?q={search_term_string}`,
    },
    "query-input": "required name=search_term_string",
  },
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${saira.variable} ${pinnacle.variable} ${splineMono.variable} h-full antialiased`}
    >
      <body className="min-h-full bg-background text-foreground">
        <a
          href="#main-content"
          className="sr-only focus:not-sr-only focus:absolute focus:left-4 focus:top-4 focus:z-50 focus:rounded-md focus:border focus:border-border focus:bg-card focus:px-4 focus:py-2 focus:font-mono focus:text-sm focus:text-foreground focus:outline-none focus:ring-2 focus:ring-ring"
        >
          Skip to main content
        </a>
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: JSON.stringify(WEBSITE_JSON_LD) }}
        />
        <ThemeProvider>
          <NuqsAdapter>
            <AnalyticsProvider>
              {/* z-1 stacking context lifts all content above the fixed
                  graph-paper grid (body::before, z-0). */}
              <div className="relative z-[1] flex min-h-full flex-col">
                <StatusStrip />
                <SiteNav />
                <div id="main-content" tabIndex={-1} className="flex-1 outline-none">
                  {children}
                </div>
                <SiteFooter />
              </div>
              {/* Vercel Speed Insights (Web Vitals). Loads its script and
                  beacons vitals from the same-origin /_vercel/speed-insights/*
                  paths (rewritten at Vercel's edge), so the enforcing CSP's
                  script-src/connect-src 'self' already cover it. No-op when not
                  deployed on Vercel. */}
              <SpeedInsights />
            </AnalyticsProvider>
          </NuqsAdapter>
        </ThemeProvider>
      </body>
    </html>
  );
}
